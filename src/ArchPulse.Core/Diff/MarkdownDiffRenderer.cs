using System.Text;

namespace ArchPulse.Core.Diff;

/// <summary>
/// Renders an architecture diff for a pull request comment or CI summary.
/// </summary>
public static class MarkdownDiffRenderer
{
    public static string Render(
        ArchitectureDiff diff,
        string beforeLabel,
        string afterLabel)
    {
        var builder = new StringBuilder();
        builder.AppendLine("# ArchPulse architecture diff");
        builder.AppendLine();
        builder.AppendLine($"**Before:** `{beforeLabel}`  ");
        builder.AppendLine($"**After:** `{afterLabel}`");
        builder.AppendLine();

        if (!diff.HasChanges)
        {
            builder.AppendLine("No architectural changes detected.");
            return builder.ToString();
        }

        builder.AppendLine(
            $"+{diff.AddedComponents.Count} / -{diff.RemovedComponents.Count} components · "
            + $"+{diff.AddedDependencies.Count} / -{diff.RemovedDependencies.Count} dependencies · "
            + $"{diff.NewViolations.Count} new / {diff.ResolvedViolations.Count} resolved violations");
        builder.AppendLine();

        AppendComponents(builder, "Added components", diff.AddedComponents, "+");
        AppendComponents(builder, "Removed components", diff.RemovedComponents, "-");

        if (diff.AddedDependencies.Count > 0)
        {
            builder.AppendLine("## Added dependencies");
            builder.AppendLine();
            foreach (var dependency in diff.AddedDependencies)
            {
                builder.AppendLine($"- `+` {dependency.From} → {dependency.To} ({dependency.Kind})");
            }

            builder.AppendLine();
        }

        if (diff.RemovedDependencies.Count > 0)
        {
            builder.AppendLine("## Removed dependencies");
            builder.AppendLine();
            foreach (var dependency in diff.RemovedDependencies)
            {
                builder.AppendLine($"- `-` {dependency.From} → {dependency.To} ({dependency.Kind})");
            }

            builder.AppendLine();
        }

        if (diff.NewViolations.Count > 0)
        {
            builder.AppendLine("## New violations");
            builder.AppendLine();
            foreach (var violation in diff.NewViolations)
            {
                builder.AppendLine(
                    $"- **{violation.Severity}** `{violation.RuleId}` — {violation.Message}");
            }

            builder.AppendLine();
        }

        if (diff.ResolvedViolations.Count > 0)
        {
            builder.AppendLine("## Resolved violations");
            builder.AppendLine();
            foreach (var violation in diff.ResolvedViolations)
            {
                builder.AppendLine(
                    $"- **{violation.Severity}** `{violation.RuleId}` — {violation.Message}");
            }

            builder.AppendLine();
        }

        builder.AppendLine("---");
        builder.AppendLine();
        builder.AppendLine("Generated by [ArchPulse](https://github.com/vinycalves/archpulse).");
        return builder.ToString();
    }

    private static void AppendComponents(
        StringBuilder builder,
        string title,
        IReadOnlyList<ArchPulse.Core.Model.ArchitectureComponent> components,
        string marker)
    {
        if (components.Count == 0)
        {
            return;
        }

        builder.AppendLine($"## {title}");
        builder.AppendLine();
        foreach (var component in components)
        {
            builder.AppendLine($"- `{marker}` **{component.Name}** ({component.Kind}, {component.Layer})");
        }

        builder.AppendLine();
    }
}
