using System.Text;
using ArchPulse.Core.Model;

namespace ArchPulse.Core.Rendering;

/// <summary>
/// Produces a review-friendly Markdown report from a scan outcome.
/// </summary>
public static class MarkdownReportRenderer
{
    public static string Render(
        ScanOutcome outcome,
        string source,
        DateTimeOffset generatedAt)
    {
        var summary = outcome.Summary;
        var builder = new StringBuilder();

        builder.AppendLine("# ArchPulse architecture report");
        builder.AppendLine();
        builder.AppendLine($"**Source:** `{EscapeCell(source)}`  ");
        builder.AppendLine($"**Generated:** {generatedAt:u}  ");
        builder.AppendLine($"**Components:** {summary.Components} · **Dependencies:** {summary.Dependencies} · **Violations:** {summary.Violations}");
        builder.AppendLine();

        builder.AppendLine("## Summary");
        builder.AppendLine();
        builder.AppendLine("| Metric | Value |");
        builder.AppendLine("|---|---:|");
        builder.AppendLine($"| Components | {summary.Components} |");
        builder.AppendLine($"| Dependencies | {summary.Dependencies} |");
        builder.AppendLine($"| Services | {summary.Services} |");
        builder.AppendLine($"| Violations | {summary.Violations} |");
        builder.AppendLine($"| Errors | {summary.Errors} |");
        builder.AppendLine($"| Warnings | {summary.Warnings} |");
        builder.AppendLine($"| Cycles | {summary.Cycles} |");
        builder.AppendLine();

        builder.AppendLine("## Architecture diagram");
        builder.AppendLine();
        builder.AppendLine("```mermaid");
        builder.Append(MermaidRenderer.Render(outcome.Graph));
        builder.AppendLine("```");
        builder.AppendLine();

        builder.AppendLine("## Components");
        builder.AppendLine();
        if (outcome.Graph.Components.Count == 0)
        {
            builder.AppendLine("No components were discovered.");
        }
        else
        {
            builder.AppendLine("| Component | Kind | Layer | Path |");
            builder.AppendLine("|---|---|---|---|");
            foreach (var component in outcome.Graph.Components
                         .OrderBy(component => component.Layer, StringComparer.OrdinalIgnoreCase)
                         .ThenBy(component => component.Name, StringComparer.OrdinalIgnoreCase))
            {
                builder.AppendLine(
                    $"| {EscapeCell(component.Name)} | {component.Kind} | {EscapeCell(component.Layer)} | `{EscapeCell(component.ProjectPath ?? string.Empty)}` |");
            }
        }

        builder.AppendLine();
        builder.AppendLine("## Dependencies");
        builder.AppendLine();
        if (outcome.Graph.Dependencies.Count == 0)
        {
            builder.AppendLine("No dependencies were discovered.");
        }
        else
        {
            builder.AppendLine("| From | To | Kind | Evidence |");
            builder.AppendLine("|---|---|---|---|");
            foreach (var dependency in outcome.Graph.Dependencies)
            {
                var from = outcome.Graph.FindComponent(dependency.From)?.Name ?? dependency.From;
                var to = outcome.Graph.FindComponent(dependency.To)?.Name ?? dependency.To;
                builder.AppendLine(
                    $"| {EscapeCell(from)} | {EscapeCell(to)} | {dependency.Kind} | {EscapeCell(dependency.Evidence ?? string.Empty)} |");
            }
        }

        builder.AppendLine();
        builder.AppendLine("## Violations");
        builder.AppendLine();
        if (outcome.Violations.Count == 0)
        {
            builder.AppendLine("No architecture violations found. Keep the boundaries healthy.");
        }
        else
        {
            builder.AppendLine("| Rule | Severity | Title | Details |");
            builder.AppendLine("|---|---|---|---|");
            foreach (var violation in outcome.Violations)
            {
                builder.AppendLine(
                    $"| {violation.RuleId} | {violation.Severity} | {EscapeCell(violation.Title)} | {EscapeCell(violation.Message)} |");
            }
        }

        builder.AppendLine();
        builder.AppendLine("---");
        builder.AppendLine();
        builder.AppendLine("Generated by [ArchPulse](https://github.com/vinycalves/archpulse).");

        return builder.ToString();
    }

    private static string EscapeCell(string value) =>
        value.Replace("|", "\\|", StringComparison.Ordinal)
            .Replace("\r", " ", StringComparison.Ordinal)
            .Replace("\n", " ", StringComparison.Ordinal);
}
